function message(lang, key) {
  const table = MESSAGES[lang] || MESSAGES.en;
  return table[key] ?? MESSAGES.en[key] ?? key;
}

function applyTranslations(lang, root = document) {
  const normalizedLang = lang === 'zh' ? 'zh' : 'en';
  root.querySelectorAll('[data-i18n]').forEach(element => {
    const key = element.getAttribute('data-i18n');
    if (key) element.textContent = message(normalizedLang, key);
  });
  root.querySelectorAll('[data-i18n-title]').forEach(element => {
    const key = element.getAttribute('data-i18n-title');
    if (key) element.title = message(normalizedLang, key);
  });
  root.querySelectorAll('[data-i18n-placeholder]').forEach(element => {
    const key = element.getAttribute('data-i18n-placeholder');
    if (key) element.placeholder = message(normalizedLang, key);
  });
  root.querySelectorAll('[data-i18n-aria-label]').forEach(element => {
    const key = element.getAttribute('data-i18n-aria-label');
    if (key) element.setAttribute('aria-label', message(normalizedLang, key));
  });
  root.querySelectorAll('[data-i18n-alt]').forEach(element => {
    const key = element.getAttribute('data-i18n-alt');
    if (key) element.alt = message(normalizedLang, key);
  });
}

function currentLanguageFromStorage(callback) {
  chrome.storage.local.get([LANG_STORAGE_KEY], result => {
    callback(result[LANG_STORAGE_KEY] === 'en' ? 'en' : 'zh');
  });
}

function applyLanguage(lang, root = document) {
  const normalizedLang = lang === 'en' ? 'en' : 'zh';
  document.documentElement.lang = normalizedLang === 'zh' ? 'zh-CN' : 'en';
  applyTranslations(normalizedLang, root);
  document.querySelectorAll('[data-lang-option]').forEach(button => {
    const active = button.getAttribute('data-lang-option') === normalizedLang;
    button.classList.toggle('is-active', active);
    button.setAttribute('aria-pressed', String(active));
  });
}

function initializeLanguageSwitch(root = document) {
  const switcher = root.querySelector('[data-language-switch]');
  if (!switcher) return;

  const setLanguage = nextLang => {
    chrome.storage.local.set({ [LANG_STORAGE_KEY]: nextLang }, () => {
      applyLanguage(nextLang, root);
      root.dispatchEvent(new CustomEvent('wos-aide:language-changed', { detail: { language: nextLang } }));
    });
  };

  switcher.addEventListener('click', event => {
    const button = event.target.closest('[data-lang-option]');
    if (!button) return;
    const nextLang = button.getAttribute('data-lang-option') === 'en' ? 'en' : 'zh';
    setLanguage(nextLang);
  });

  root.addEventListener('keydown', event => {
    if (event.defaultPrevented || event.isComposing || event.repeat) return;
    if (!(event.metaKey || event.ctrlKey) || !event.shiftKey || event.altKey) return;
    if (String(event.key || '').toLowerCase() !== 'e') return;
    event.preventDefault();
    const currentLang = document.documentElement.lang === 'en' ? 'en' : 'zh';
    setLanguage(currentLang === 'en' ? 'zh' : 'en');
  });

  applyLanguage('zh', root);
  currentLanguageFromStorage(lang => applyLanguage(lang, root));
}

